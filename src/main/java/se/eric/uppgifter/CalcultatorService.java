package se.eric.uppgifter;

public class CalcultatorService {

    public double addera(double number1, double number2) {
        return number1 + number2;
    }

    public int subtrahera(int number1, int number2) {
        return number1 - number2;
    }

    public double dividera(double number1, double number2) {
        return number1 / number2;
    }

    public int multiplera(int number1, int number2) {
        return number1 * number2;
    }
}
